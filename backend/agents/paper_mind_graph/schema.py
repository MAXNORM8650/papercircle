@dataclass
class SourceLocation:
    """Location in the original PDF."""
    page: int
    bbox: Optional[tuple] = None  # (x0, y0, x1, y1)
    line_start: Optional[int] = None
    line_end: Optional[int] = None
    char_start: Optional[int] = None
    char_end: Optional[int] = None
    
    def to_dict(self) -> Dict:
        return {
            "page": self.page,
            "bbox": self.bbox,
            "line_start": self.line_start,
            "line_end": self.line_end,
            "char_start": self.char_start,
            "char_end": self.char_end
        }
    
    @classmethod
    def from_dict(cls, d: Dict) -> 'SourceLocation':
        return cls(**d)


@dataclass
class Chunk:
    """A semantic chunk of the paper."""
    id: str
    text: str
    source_type: Literal["body", "figure", "table", "equation", "caption", "abstract"]
    section_id: Optional[str] = None
    page_span: tuple = (0, 0)
    source_locations: List[SourceLocation] = field(default_factory=list)
    embedding: Optional[List[float]] = None
    
    def to_dict(self) -> Dict:
        return {
            "id": self.id,
            "text": self.text,
            "source_type": self.source_type,
            "section_id": self.section_id,
            "page_span": self.page_span,
            "source_locations": [loc.to_dict() for loc in self.source_locations]
        }


@dataclass
class GraphNode:
    """A node in the mind graph."""
    id: str
    type: NodeType
    title: str
    description: str = ""
    
    # Source tracking
    source_chunks: List[str] = field(default_factory=list)  # Chunk IDs
    origin_pages: List[int] = field(default_factory=list)
    source_locations: List[SourceLocation] = field(default_factory=list)
    
    # For figures/tables
    label: Optional[str] = None  # "Figure 3", "Table 1"
    caption: Optional[str] = None
    image_path: Optional[str] = None
    
    # For equations
    latex: Optional[str] = None
    equation_number: Optional[str] = None
    
    # Metadata
    verification_status: VerificationStatus = VerificationStatus.AUTO_GENERATED
    confidence: float = 1.0
    created_at: str = field(default_factory=lambda: datetime.now().isoformat())
    modified_at: Optional[str] = None
    modified_by: Optional[str] = None  # "auto" or user ID
    
    # Additional properties
    properties: Dict[str, Any] = field(default_factory=dict)
    
    def to_dict(self) -> Dict:
        return {
            "id": self.id,
            "type": self.type.value,
            "title": self.title,
            "description": self.description,
            "source_chunks": self.source_chunks,
            "origin_pages": self.origin_pages,
            "source_locations": [loc.to_dict() for loc in self.source_locations],
            "label": self.label,
            "caption": self.caption,
            "image_path": self.image_path,
            "latex": self.latex,
            "equation_number": self.equation_number,
            "verification_status": self.verification_status.value,
            "confidence": self.confidence,
            "created_at": self.created_at,
            "modified_at": self.modified_at,
            "modified_by": self.modified_by,
            "properties": self.properties
        }
    
    @classmethod
    def from_dict(cls, d: Dict) -> 'GraphNode':
        d = d.copy()
        d["type"] = NodeType(d["type"])
        d["verification_status"] = VerificationStatus(d.get("verification_status", "auto"))
        d["source_locations"] = [SourceLocation.from_dict(loc) for loc in d.get("source_locations", [])]
        return cls(**d)


@dataclass
class GraphEdge:
    """An edge in the mind graph."""
    id: str
    type: EdgeType
    source_id: str  # Source node ID
    target_id: str  # Target node ID
    
    # Edge metadata
    label: Optional[str] = None  # Optional label/description
    reason: Optional[str] = None  # Why this edge exists
    weight: float = 1.0
    
    # Source tracking
    source_chunks: List[str] = field(default_factory=list)
    
    # Verification
    verification_status: VerificationStatus = VerificationStatus.AUTO_GENERATED
    confidence: float = 1.0
    created_at: str = field(default_factory=lambda: datetime.now().isoformat())
    
    def to_dict(self) -> Dict:
        return {
            "id": self.id,
            "type": self.type.value,
            "source_id": self.source_id,
            "target_id": self.target_id,
            "label": self.label,
            "reason": self.reason,
            "weight": self.weight,
            "source_chunks": self.source_chunks,
            "verification_status": self.verification_status.value,
            "confidence": self.confidence,
            "created_at": self.created_at
        }
    
    @classmethod
    def from_dict(cls, d: Dict) -> 'GraphEdge':
        d = d.copy()
        d["type"] = EdgeType(d["type"])
        d["verification_status"] = VerificationStatus(d.get("verification_status", "auto"))
        return cls(**d)


