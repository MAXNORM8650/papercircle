"""
Paper Mind Graph - Data Models & Schema
========================================
Defines the node types, edge types, and data structures for the paper mind graph.
"""

from dataclasses import dataclass, field
from typing import Optional, List, Dict, Any, Literal
from enum import Enum
import json
from datetime import datetime
import uuid


# ============================================================================
# Node Types
# ============================================================================

class NodeType(str, Enum):
    """Types of nodes in the mind graph."""
    PAPER = "paper"           # Root node
    SECTION = "section"       # Paper sections/subsections
    CONCEPT = "concept"       # Key ideas, definitions
    METHOD = "method"         # Algorithms, architectures
    EXPERIMENT = "experiment" # Experimental setup/results
    FIGURE = "figure"         # Figures with captions
    TABLE = "table"           # Tables with captions
    EQUATION = "equation"     # Mathematical equations
    DATASET = "dataset"       # Datasets mentioned
    TASK = "task"             # Tasks/benchmarks
    RESULT = "result"         # Specific results/findings
    LIMITATION = "limitation" # Limitations mentioned
    FUTURE_WORK = "future_work"  # Future directions
    REFERENCE = "reference"   # Cited papers


class EdgeType(str, Enum):
    """Types of edges in the mind graph."""
    # Structural edges
    HAS_SECTION = "has_section"
    HAS_SUBSECTION = "has_subsection"
    
    # Content edges
    DEFINES = "defines"           # Section/Chunk defines Concept
    USES_METHOD = "uses_method"   # Experiment uses Method
    PROPOSES = "proposes"         # Paper/Section proposes Method
    EVALUATES_ON = "evaluates_on" # Experiment evaluates on Dataset/Task
    
    # Visual/Reference edges
    ILLUSTRATED_BY = "illustrated_by"  # Concept/Method → Figure
    SUMMARIZED_BY = "summarized_by"    # Results → Table
    DERIVED_BY = "derived_by"          # Concept → Equation
    
    # Semantic edges
    DEPENDS_ON = "depends_on"     # Concept depends on Concept
    EXTENDS = "extends"           # Method extends another Method
    COMPARES_TO = "compares_to"   # Experiment compares to baseline
    SUPPORTS = "supports"         # Result supports Concept
    CONTRADICTS = "contradicts"   # Result contradicts prior work
    CITES = "cites"               # Paper cites Reference
    
    # Relationship edges
    RELATED_TO = "related_to"     # General relationship
    PART_OF = "part_of"           # Component relationship


class VerificationStatus(str, Enum):
    """Verification status of nodes/edges."""
    AUTO_GENERATED = "auto"      # Generated by LLM
    HUMAN_VERIFIED = "verified"  # Human approved
    HUMAN_EDITED = "edited"      # Human modified
    FLAGGED = "flagged"          # Needs review


