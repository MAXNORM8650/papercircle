@dataclass
class MindGraph:
    """The complete mind graph for a paper."""
    paper_id: str
    metadata: PaperMetadata
    
    # Parsed structure
    sections: List[Section] = field(default_factory=list)
    figures: List[Figure] = field(default_factory=list)
    tables: List[Table] = field(default_factory=list)
    equations: List[Equation] = field(default_factory=list)
    
    # Chunks for retrieval
    chunks: List[Chunk] = field(default_factory=list)
    
    # Graph structure
    nodes: Dict[str, GraphNode] = field(default_factory=dict)
    edges: Dict[str, GraphEdge] = field(default_factory=dict)
    
    # Metadata
    created_at: str = field(default_factory=lambda: datetime.now().isoformat())
    modified_at: Optional[str] = None
    version: str = "1.0"
    
    def add_node(self, node: GraphNode) -> str:
        """Add a node to the graph."""
        self.nodes[node.id] = node
        self.modified_at = datetime.now().isoformat()
        return node.id
    
    def add_edge(self, edge: GraphEdge) -> str:
        """Add an edge to the graph."""
        self.edges[edge.id] = edge
        self.modified_at = datetime.now().isoformat()
        return edge.id
    
    def get_node(self, node_id: str) -> Optional[GraphNode]:
        """Get a node by ID."""
        return self.nodes.get(node_id)
    
    def get_edges_from(self, node_id: str) -> List[GraphEdge]:
        """Get all edges originating from a node."""
        return [e for e in self.edges.values() if e.source_id == node_id]
    
    def get_edges_to(self, node_id: str) -> List[GraphEdge]:
        """Get all edges pointing to a node."""
        return [e for e in self.edges.values() if e.target_id == node_id]
    
    def get_neighbors(self, node_id: str, hops: int = 1) -> Dict[str, GraphNode]:
        """Get neighboring nodes within n hops."""
        visited = {node_id}
        current_level = {node_id}
        
        for _ in range(hops):
            next_level = set()
            for nid in current_level:
                # Get connected nodes
                for edge in self.get_edges_from(nid):
                    if edge.target_id not in visited:
                        next_level.add(edge.target_id)
                for edge in self.get_edges_to(nid):
                    if edge.source_id not in visited:
                        next_level.add(edge.source_id)
            visited.update(next_level)
            current_level = next_level
        
        return {nid: self.nodes[nid] for nid in visited if nid in self.nodes}
    
    def get_nodes_by_type(self, node_type: NodeType) -> List[GraphNode]:
        """Get all nodes of a specific type."""
        return [n for n in self.nodes.values() if n.type == node_type]
    
    def get_subgraph(self, node_ids: List[str]) -> 'MindGraph':
        """Get a subgraph containing only specified nodes and their edges."""
        subgraph = MindGraph(
            paper_id=self.paper_id,
            metadata=self.metadata
        )
        
        node_set = set(node_ids)
        for nid in node_ids:
            if nid in self.nodes:
                subgraph.nodes[nid] = self.nodes[nid]
        
        for edge in self.edges.values():
            if edge.source_id in node_set and edge.target_id in node_set:
                subgraph.edges[edge.id] = edge
        
        return subgraph
    
    def to_dict(self) -> Dict:
        """Convert to dictionary for serialization."""
        return {
            "paper_id": self.paper_id,
            "metadata": self.metadata.to_dict(),
            "sections": [s.to_dict() for s in self.sections],
            "figures": [f.to_dict() for f in self.figures],
            "tables": [t.to_dict() for t in self.tables],
            "equations": [e.to_dict() for e in self.equations],
            "chunks": [c.to_dict() for c in self.chunks],
            "nodes": {k: v.to_dict() for k, v in self.nodes.items()},
            "edges": {k: v.to_dict() for k, v in self.edges.items()},
            "created_at": self.created_at,
            "modified_at": self.modified_at,
            "version": self.version
        }
    
    def to_json(self, indent: int = 2) -> str:
        """Convert to JSON string."""
        return json.dumps(self.to_dict(), indent=indent)
    
    @classmethod
    def from_dict(cls, d: Dict) -> 'MindGraph':
        """Create from dictionary."""
        graph = cls(
            paper_id=d["paper_id"],
            metadata=PaperMetadata(**d["metadata"])
        )
        # Load sections, figures, etc.
        graph.sections = [Section(**s) for s in d.get("sections", [])]
        graph.figures = [Figure(**f) for f in d.get("figures", [])]
        graph.tables = [Table(**t) for t in d.get("tables", [])]
        graph.equations = [Equation(**e) for e in d.get("equations", [])]
        
        # Load chunks
        for c in d.get("chunks", []):
            chunk = Chunk(
                id=c["id"],
                text=c["text"],
                source_type=c["source_type"],
                section_id=c.get("section_id"),
                page_span=tuple(c.get("page_span", (0, 0)))
            )
            graph.chunks.append(chunk)
        
        # Load nodes and edges
        for k, v in d.get("nodes", {}).items():
            graph.nodes[k] = GraphNode.from_dict(v)
        for k, v in d.get("edges", {}).items():
            graph.edges[k] = GraphEdge.from_dict(v)
        
        graph.created_at = d.get("created_at", graph.created_at)
        graph.modified_at = d.get("modified_at")
        graph.version = d.get("version", "1.0")
        
        return graph


# ============================================================================
# Helper Functions
# ============================================================================

def generate_id(prefix: str = "") -> str:
    """Generate a unique ID."""
    short_uuid = str(uuid.uuid4())[:8]
    if prefix:
        return f"{prefix}_{short_uuid}"
    return short_uuid


def create_edge(
    edge_type: EdgeType,
    source_id: str,
    target_id: str,
    reason: str = None,
    source_chunks: List[str] = None
) -> GraphEdge:
    """Helper to create an edge."""
    return GraphEdge(
        id=generate_id("edge"),
        type=edge_type,
        source_id=source_id,
        target_id=target_id,
        reason=reason,
        source_chunks=source_chunks or []
    )


def create_node(
    node_type: NodeType,
    title: str,
    description: str = "",
    source_chunks: List[str] = None,
    origin_pages: List[int] = None,
    **kwargs
) -> GraphNode:
    """Helper to create a node."""
    prefix = node_type.value
    return GraphNode(
        id=generate_id(prefix),
        type=node_type,
        title=title,
        description=description,
        source_chunks=source_chunks or [],
        origin_pages=origin_pages or [],
        **kwargs
    )
